function normalizeRiskPpeCatalogText(value = "") {
  return String(value || "")
    .normalize("NFD")
    .replace(/[đĐ]/g, "d")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

function isRiskPpeEquipmentCatalogItem(item = {}) {
  const name = normalizeRiskPpeCatalogText(item.name);
  const methodOnlyPatterns = [
    "metoda",
    "odredivanje",
    "mjerenje",
    "ocjenjivanje",
    "procjena postojecih",
    "subjektivna metoda",
    "nazivlje",
    "ispitivanje na probijanje"
  ];
  return !methodOnlyPatterns.some((pattern) => name.includes(pattern));
}

