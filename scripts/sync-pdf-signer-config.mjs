import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const rootDir = process.cwd();
const configPath = resolve(rootDir, "browser-extension", "pdf-signer-bridge", "pdf-signer.config.json");
const nativeHostPath = resolve(rootDir, "browser-extension", "pdf-signer-bridge", "native-host.json");
const extensionRuntimeConfigPath = resolve(rootDir, "browser-extension", "pdf-signer-bridge", "pdf-signer.config.js");
const manifestPath = resolve(rootDir, "browser-extension", "pdf-signer-bridge", "manifest.json");
const frontendConfigPath = resolve(rootDir, "src", "pdfSignerExtensionConfig.js");

function cleanString(value = "") {
  return String(value || "").trim();
}

function cleanMatches(values = []) {
  return (Array.isArray(values) ? values : [])
    .map(cleanString)
    .filter(Boolean);
}

const config = JSON.parse(await readFile(configPath, "utf8"));
const extensionId = cleanString(config.extensionId);
const nativeHostName = cleanString(config.nativeHostName || "hr.abeceda.pdfsigner");
const nativeHostDescription = cleanString(config.nativeHostDescription || "SafeNexus PDF Signer Native Host");
const nativeHostExePath = cleanString(config.nativeHostPath || "C:\\Program Files\\PDFSigner\\PDFSigner.exe");
const installUrl = cleanString(config.installUrl || "/browser-extension/pdf-signer-bridge/README.md");
const externallyConnectableMatches = cleanMatches(config.externallyConnectableMatches);

if (!/^[a-p]{32}$/.test(extensionId)) {
  throw new Error(`Invalid Chrome extension ID in ${configPath}: ${extensionId}`);
}

if (!nativeHostName) {
  throw new Error("nativeHostName is required.");
}

const nativeHost = {
  name: nativeHostName,
  description: nativeHostDescription,
  path: nativeHostExePath,
  type: "stdio",
  allowed_origins: [
    `chrome-extension://${extensionId}/`,
  ],
};

const manifest = {
  manifest_version: 3,
  name: "SafeNexus PDF Signer Bridge",
  description: "Connects SafeNexus web app with the local PDF signer through Chrome Native Messaging.",
  version: "0.1.0",
  permissions: [
    "nativeMessaging",
  ],
  background: {
    service_worker: "background.js",
  },
  externally_connectable: {
    matches: externallyConnectableMatches,
  },
};

const extensionRuntimeConfig = `// Generated by scripts/sync-pdf-signer-config.mjs. Edit pdf-signer.config.json instead.\nself.SAFE_NEXUS_PDF_SIGNER_CONFIG = ${JSON.stringify({
  nativeHostName,
}, null, 2)};\n`;

const frontendConfig = `// Generated by scripts/sync-pdf-signer-config.mjs. Edit browser-extension/pdf-signer-bridge/pdf-signer.config.json instead.\nexport const PDF_SIGNER_EXTENSION_ID = ${JSON.stringify(extensionId)};\nexport const PDF_SIGNER_EXTENSION_INSTALL_URL = ${JSON.stringify(installUrl)};\n`;

await mkdir(dirname(nativeHostPath), { recursive: true });
await mkdir(dirname(frontendConfigPath), { recursive: true });

await writeFile(nativeHostPath, `${JSON.stringify(nativeHost, null, 2)}\n`, "utf8");
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
await writeFile(extensionRuntimeConfigPath, extensionRuntimeConfig, "utf8");
await writeFile(frontendConfigPath, frontendConfig, "utf8");

console.log(`PDF signer config synced for extension ${extensionId}.`);
